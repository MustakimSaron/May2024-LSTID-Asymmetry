def load_sector_tec(filepath):
    with h5py.File(filepath, "r") as h5:
        table = h5["Data"]["Table Layout"][:]
        glon = (table["glon"] + 180) % 360 - 180
        gdlat = table["gdlat"]
        mask = (
            (((glon >= 25) & (glon <= 45)) | ((glon >= -90) & (glon <= -70)))
            & (gdlat >= 28) & (gdlat <= 72)
        )
        sub = table[mask]
        df = pd.DataFrame({
            "year": sub["year"].astype(int),
            "month": sub["month"].astype(int),
            "day": sub["day"].astype(int),
            "hour": sub["hour"].astype(int),
            "minute": sub["min"].astype(int),
            "second": sub["sec"].astype(int),
            "lat": sub["gdlat"].astype(float),
            "lon": glon[mask].astype(float),
            "tec": sub["tec"].astype(float),
        })
    df = df[(df["tec"] >= 0) & (df["tec"] <= 350)]
    df["Timestamp"] = pd.to_datetime(df[["year", "month", "day", "hour", "minute", "second"]])
    return df[["Timestamp", "lat", "lon", "tec"]]


