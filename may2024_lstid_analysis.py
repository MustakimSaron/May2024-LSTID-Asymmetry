def centered_dipole_mlat(lat_deg, lon_deg, pole_lat=80.5, pole_lon=-72.5):
    phi, lam = np.radians(lat_deg), np.radians(lon_deg)
    phi_p, lam_p = np.radians(pole_lat), np.radians(pole_lon)
    sin_mlat = np.sin(phi_p) * np.sin(phi) + np.cos(phi_p) * np.cos(phi) * np.cos(lam - lam_p)
    return np.degrees(np.arcsin(np.clip(sin_mlat, -1.0, 1.0)))


