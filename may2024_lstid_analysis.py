KM_PER_DEG = 111.132


def track_ridge_continuous(dtec_df, lat_start, lat_end, t_start_seed,
                           max_step_back_min=5, max_step_fwd_min=15, min_dtec_tecu=0.35):
    """
    Continuously tracks a single positive dTEC wavefront crest equatorward
    from lat_start to lat_end. At each 1-deg latitude step, searches only
    within [t_prev - max_step_back_min, t_prev + max_step_fwd_min] around
    the previous latitude's detected crest time t_prev (strictly < T/2),
    preventing cycle-skipping onto adjacent wave packets.
    """
    lats_out, times_out, peaks_out = [], [], []
    t_prev = pd.Timestamp(t_start_seed)

    for lat in range(lat_start, lat_end - 1, -1):
        w_start = t_prev - pd.Timedelta(minutes=max_step_back_min)
        w_end = t_prev + pd.Timedelta(minutes=max_step_fwd_min)
        series = dtec_df.loc[w_start:w_end, lat].dropna()
        if series.empty:
            continue
        t_peak = series.idxmax()
        val_peak = float(series.loc[t_peak])
        if val_peak >= min_dtec_tecu:
            lats_out.append(lat)
            times_out.append(t_peak)
            peaks_out.append(val_peak)
            t_prev = t_peak

    return np.array(lats_out, dtype=float), pd.DatetimeIndex(times_out), np.array(peaks_out, dtype=float)


def fit_phase_velocity_ols(lats, times, lat_ref):
    """
    Ordinary Least Squares (OLS) regression of equatorward distance d_i [m]
    against elapsed time dt_i [s]:
        d_i = R_E * (lat_ref - phi_i) = V_p * (t_i - t_0) + d_0
    Reports 95% confidence interval using Student-t distribution (df = N - 2).
    """
    t0 = times[0]
    dt_sec = (times - t0).total_seconds().to_numpy()
    dist_m = (lat_ref - lats) * KM_PER_DEG * 1000.0
    res = stats.linregress(dt_sec, dist_m)
    n = len(lats)
    t_crit = stats.t.ppf(0.975, df=n - 2)
    return {
        "vp": res.slope,
        "ci95": res.stderr * t_crit,
        "stderr": res.stderr,
        "r2": res.rvalue ** 2,
        "intercept_m": res.intercept,
        "t0": t0,
        "lat_ref": lat_ref,
        "n": n,
        "p_value": res.pvalue,
    }


