def run_welch(sig, nperseg, noverlap):
    f, psd = welch(sig, fs=fs, window="hann", nperseg=nperseg, noverlap=noverlap, detrend="linear")
    periods = (1.0 / f[1:]) / 60.0
    psd = psd[1:]
    m = (periods >= 20) & (periods <= 120)
    peak_t = periods[m][np.argmax(psd[m])]
    df_mhz = (fs / nperseg) * 1000.0
    return periods, psd, peak_t, df_mhz


