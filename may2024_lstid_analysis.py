def build_grids(df_data, lon_min, lon_max, t0, t1, lat_min=30, lat_max=70, win_samples=12):
    sub = df_data[
        (df_data["lon"] >= lon_min) & (df_data["lon"] <= lon_max)
        & (df_data["lat"] >= lat_min) & (df_data["lat"] <= lat_max)
        & (df_data["Timestamp"] >= t0) & (df_data["Timestamp"] <= t1)
    ].copy()
    sub["lat_bin"] = np.round(sub["lat"]).astype(int)
    sub["time_bin"] = sub["Timestamp"].dt.floor("5min")
    vtec_grid = sub.groupby(["time_bin", "lat_bin"])["tec"].mean().unstack(level="lat_bin")
    vtec_grid = vtec_grid.reindex(
        index=pd.date_range(t0, t1, freq="5min"),
        columns=np.arange(lat_min, lat_max + 1),
    )
    trend = vtec_grid.rolling(window=win_samples, center=True, min_periods=3).mean()
    dtec_grid = vtec_grid - trend
    return vtec_grid, dtec_grid


